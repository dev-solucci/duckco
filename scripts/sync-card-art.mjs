// Scans public/brand/cards and writes src/data/cardArt.ts mapping each card id
// to its art file. Runs automatically before dev and build (predev, prebuild).
// Drop an image named <card-id>.<ext> into public/brand/cards and it appears.

import { readdirSync, writeFileSync, existsSync, mkdirSync } from "fs";
import { join } from "path";

const root = process.cwd();
const dir = join(root, "public", "brand", "cards");
if (!existsSync(dir)) mkdirSync(dir, { recursive: true });

const exts = new Set([".png", ".jpg", ".jpeg", ".webp", ".avif"]);
const map = {};

for (const file of readdirSync(dir).sort()) {
  const dot = file.lastIndexOf(".");
  if (dot <= 0) continue;
  const ext = file.slice(dot).toLowerCase();
  if (!exts.has(ext)) continue;
  const id = file.slice(0, dot);
  map[id] = `/brand/cards/${file}`;
}

const out = `// Generated by scripts/sync-card-art.mjs. Do not edit by hand.
// Maps a card id to its art file under public/brand/cards.
export const cardArt: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;

writeFileSync(join(root, "src", "data", "cardArt.ts"), out);
console.log(`Synced ${Object.keys(map).length} card art file(s).`);
